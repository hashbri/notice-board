-- ============================================================
-- notice-board 建库脚本
--
-- 怎么执行（二选一）：
--   A. phpMyAdmin：选中 notice_board 库 → SQL 标签页 → 粘贴 → 执行
--   B. 命令行：mysql -u root -p < schema.sql
--
-- ⚠️ 这个脚本会先 DROP 再 CREATE，重复执行会清空已有数据。
-- ============================================================

CREATE DATABASE IF NOT EXISTS notice_board
    DEFAULT CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE notice_board;

DROP TABLE IF EXISTS articles;

CREATE TABLE articles (
    id          INT UNSIGNED NOT NULL AUTO_INCREMENT,
    title       VARCHAR(100) NOT NULL                COMMENT '标题，限 100 字',
    content     TEXT         NOT NULL                COMMENT '正文',
    status      TINYINT      NOT NULL DEFAULT 0      COMMENT '0=草稿 1=已发布',
    created_at  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    deleted_at  DATETIME     NULL     DEFAULT NULL   COMMENT '非空 = 已软删除',
    PRIMARY KEY (id),
    KEY idx_list (status, deleted_at, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='公告资讯';


